import re
from typing import Dict, Optional

from nvflare.apis.shareable import Shareable

from .defs import Constant

# Hop-by-hop headers and headers describing the message framing. Each hop of the tunnel sets these itself, so they
# must not be forwarded. "date" and "server" are generated by the HTTP server that writes the response.
_NON_FORWARDED_HEADERS = frozenset(
    {
        "connection",
        "keep-alive",
        "proxy-connection",
        "proxy-authenticate",
        "proxy-authorization",
        "te",
        "trailer",
        "transfer-encoding",
        "upgrade",
        "content-length",
        "host",
        "date",
        "server",
    }
)

# Only the Fleet API is ever tunneled. The SuperLink's Control and Runtime APIs share its port but must never be
# reachable from a FLARE client.
FLEET_PATH_PREFIX = "/v1/fleet/"
_FLEET_PATH_PATTERN = re.compile(r"^/v1/fleet/[A-Za-z0-9_-]+(/[A-Za-z0-9_-]+)*$")


def is_fleet_path(path: Optional[str]) -> bool:
    """Check whether the path is a well-formed Fleet API path (no query string, no dot segments)."""
    return isinstance(path, str) and _FLEET_PATH_PATTERN.match(path) is not None


def filter_headers(headers) -> Dict[str, str]:
    """Return a plain dict of the headers that can be forwarded through the tunnel.

    Args:
        headers: a mapping, an iterable of (name, value) pairs, or None

    Returns: dict of str to str without hop-by-hop and framing headers
    """
    if not headers:
        return {}
    pairs = headers.items() if hasattr(headers, "items") else headers
    return {str(k): str(v) for k, v in pairs if str(k).lower() not in _NON_FORWARDED_HEADERS}


def request_to_shareable(path: str, headers, body: bytes) -> Shareable:
    """Pack an HTTP request made by a Flower SuperNode into a Shareable (to be sent to the FLARE server)."""
    s = Shareable()
    s[Constant.PARAM_KEY_MSG_NAME] = path
    s[Constant.PARAM_KEY_HEADERS] = filter_headers(headers)
    s[Constant.PARAM_KEY_CONTENT] = body if body is not None else b""
    return s


def shareable_to_request(s: Shareable):
    """Unpack a request Shareable.

    Returns: tuple of (path, headers, body)
    """
    path = s.get(Constant.PARAM_KEY_MSG_NAME)
    headers = filter_headers(s.get(Constant.PARAM_KEY_HEADERS))
    body = s.get(Constant.PARAM_KEY_CONTENT)
    return path, headers, body if body is not None else b""


def response_to_shareable(status: int, headers, body: bytes) -> Shareable:
    """Pack an HTTP response from the Flower SuperLink into a Shareable (to be sent back to the FLARE client)."""
    s = Shareable()
    s[Constant.PARAM_KEY_STATUS] = int(status)
    s[Constant.PARAM_KEY_HEADERS] = filter_headers(headers)
    s[Constant.PARAM_KEY_CONTENT] = body if body is not None else b""
    return s


def shareable_to_response(s: Shareable):
    """Unpack a response Shareable.

    Returns: tuple of (status, headers, body)

    Raises:
        ValueError: if the Shareable has no valid HTTP status
    """
    status = s.get(Constant.PARAM_KEY_STATUS)
    if not isinstance(status, int) or isinstance(status, bool) or not 100 <= status <= 599:
        raise ValueError(f"invalid HTTP status in reply: {status!r}")
    headers = filter_headers(s.get(Constant.PARAM_KEY_HEADERS))
    body = s.get(Constant.PARAM_KEY_CONTENT)
    return status, headers, body if body is not None else b""
