"""Frontend build/publish contracts without executing Node or altering packaged assets."""

import json
from pathlib import Path
from types import SimpleNamespace

import pytest

from dashboard import build_ui


@pytest.fixture
def ui(tmp_path):
    directory = tmp_path / "ui"
    directory.mkdir()
    for name in build_ui.REQUIRED_INPUTS:
        (directory / name).write_text("{}\n")
    (directory / "src").mkdir()
    (directory / "src" / "index.tsx").write_text("export default function Page() { return null }\n")
    (directory / "scripts").mkdir()
    (directory / "scripts" / "notices.mjs").write_text("// Build-time notices generator\n")
    return directory


@pytest.fixture
def exported(tmp_path):
    directory = tmp_path / "out"
    directory.mkdir()
    for name in build_ui.EXPECTED_PAGES:
        (directory / name).write_text("<!doctype html><html></html>\n")
    (directory / "index.html").write_text(
        '<!doctype html><html><link rel="stylesheet" href="styles/main.css">'
        '<script src="/nvflare-dashboard/_next/static/chunks/main.js?build=1"></script>'
        '<img src="data:image/svg+xml,svg">'
        '<link rel="canonical" href="/some-route"></html>\n'
    )
    (directory / "_next" / "static" / "chunks").mkdir(parents=True)
    (directory / "_next" / "static" / "chunks" / "main.js").write_text("console.log('Dashboard');\n")
    (directory / "styles").mkdir()
    (directory / "styles" / "main.css").write_text("body { background: url('../images/logo.svg') }\n")
    (directory / "images").mkdir()
    (directory / "images" / "logo.svg").write_text("<svg></svg>\n")
    (directory / "THIRD_PARTY_NOTICES.txt").write_text("Third-party notices\n")
    return directory


def test_source_fingerprint_tracks_build_inputs_but_not_generated_files(ui):
    initial = build_ui.source_fingerprint(ui)
    (ui / "next-env.d.ts").write_text("// Generated by Next\n")
    (ui / "tests").mkdir()
    (ui / "tests" / "page.test.tsx").write_text("// Test changes do not change the export\n")
    (ui / "README.md").write_text("Documentation changes\n")
    assert build_ui.source_fingerprint(ui) == initial
    (ui / "scripts" / "notices.mjs").write_text("// Changed notices generator\n")
    assert build_ui.source_fingerprint(ui) != initial


def test_source_fingerprint_rejects_links_outside_the_source(ui, tmp_path):
    secret = tmp_path / "outside.tsx"
    secret.write_text("outside the source tree\n")
    (ui / "src" / "linked.tsx").symlink_to(secret)
    with pytest.raises(build_ui.BuildError, match="symbolic links"):
        build_ui.source_fingerprint(ui)


def test_export_validation_requires_backend_routes_and_local_assets(exported):
    assert build_ui.validate_export(exported) == 3
    (exported / "downloads.html").unlink()
    with pytest.raises(build_ui.BuildError, match="downloads.html"):
        build_ui.validate_export(exported)


def test_export_validation_rejects_missing_assets(exported):
    (exported / "images" / "logo.svg").unlink()
    with pytest.raises(build_ui.BuildError, match="Missing exported asset"):
        build_ui.validate_export(exported)


def test_export_validation_rejects_unprefixed_or_escaping_asset_urls(exported):
    index = exported / "index.html"
    index.write_text('<script src="/unprefixed.js"></script>')
    with pytest.raises(build_ui.BuildError, match="must use /nvflare-dashboard/"):
        build_ui.validate_export(exported)
    index.write_text('<script src="/nvflare-dashboard/%2e%2e/%2e%2e/outside.js"></script>')
    with pytest.raises(build_ui.BuildError, match="escapes"):
        build_ui.validate_export(exported)


def test_build_check_detects_source_changes_and_published_asset_tampering(ui, exported):
    fingerprint = build_ui.source_fingerprint(ui)
    manifest = build_ui.write_build_manifest(exported, fingerprint)
    assert manifest["build_id"] == fingerprint[:20]
    assert build_ui.check_build(ui, exported) == manifest
    chunk = exported / "_next" / "static" / "chunks" / "main.js"
    chunk.write_text("changed bytes\n")
    with pytest.raises(build_ui.BuildError, match="contents differ"):
        build_ui.check_build(ui, exported)
    build_ui.write_build_manifest(exported, fingerprint)
    (ui / "src" / "index.tsx").write_text("export default function Page() { return 'updated' }\n")
    with pytest.raises(build_ui.BuildError, match="stale"):
        build_ui.check_build(ui, exported)


def test_publish_replaces_the_whole_generated_tree(ui, exported, tmp_path):
    destination = tmp_path / "static" / "nvflare-dashboard"
    destination.mkdir(parents=True)
    (destination / "old-kaizen.js").write_text("old generated asset\n")
    build_ui.write_build_manifest(exported, build_ui.source_fingerprint(ui))
    build_ui.publish_export(exported, destination)
    assert not (destination / "old-kaizen.js").exists()
    assert build_ui.check_build(ui, destination)
    assert not list(destination.parent.glob(".nvflare-dashboard.*"))


def test_build_check_rejects_a_nonobject_manifest(ui, exported):
    (exported / build_ui.MANIFEST_NAME).write_text("[]\n")
    with pytest.raises(build_ui.BuildError, match="manifest is missing or invalid"):
        build_ui.check_build(ui, exported)


def test_publish_rolls_back_if_new_tree_cannot_be_renamed(exported, tmp_path, monkeypatch):
    destination = tmp_path / "static" / "nvflare-dashboard"
    destination.mkdir(parents=True)
    (destination / "old.txt").write_text("previous assets\n")
    original_replace = build_ui.os.replace

    def reject_staging(source, target):
        if ".stage-" in Path(source).name:
            raise OSError("simulated publication failure")
        return original_replace(source, target)

    monkeypatch.setattr(build_ui.os, "replace", reject_staging)
    with pytest.raises(build_ui.BuildError, match="previous assets were restored"):
        build_ui.publish_export(exported, destination)
    assert (destination / "old.txt").read_text() == "previous assets\n"
    assert not list(destination.parent.glob(".nvflare-dashboard.*"))


def test_publish_rejects_destination_symlinks(exported, tmp_path):
    original = tmp_path / "original"
    original.mkdir()
    destination = tmp_path / "linked"
    destination.symlink_to(original, target_is_directory=True)
    with pytest.raises(build_ui.BuildError, match="symbolic-link"):
        build_ui.publish_export(exported, destination)
    assert destination.is_symlink()


@pytest.mark.parametrize("node,npm", [("v22.0.0", "11.0.0"), ("v24.0.0", "12.0.0")])
def test_toolchain_requires_supported_node_and_npm(node, npm, monkeypatch):
    monkeypatch.setattr(build_ui.shutil, "which", lambda name: name)
    monkeypatch.setattr(
        build_ui.subprocess,
        "run",
        lambda arguments, **kwargs: SimpleNamespace(stdout=node if arguments[0] == "node" else npm),
    )
    with pytest.raises(build_ui.BuildError, match="is required"):
        build_ui.check_toolchain()


def test_check_mode_does_not_require_node(ui, exported, monkeypatch):
    build_ui.write_build_manifest(exported, build_ui.source_fingerprint(ui))
    monkeypatch.setattr(build_ui, "check_toolchain", lambda: pytest.fail("Node must not run in check mode"))
    assert build_ui.main(["--check", "--ui-dir", str(ui), "--destination", str(exported)]) == 0
    saved = json.loads((exported / build_ui.MANIFEST_NAME).read_text())
    assert saved["schema_version"] == build_ui.MANIFEST_SCHEMA
